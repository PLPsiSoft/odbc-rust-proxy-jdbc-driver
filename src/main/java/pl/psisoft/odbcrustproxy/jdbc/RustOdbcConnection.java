package pl.psisoft.odbcrustproxy.jdbc;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.sql.Array;
import java.sql.Blob;
import java.sql.CallableStatement;
import java.sql.Clob;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.NClob;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.SQLXML;
import java.sql.Savepoint;
import java.sql.Statement;
import java.sql.Struct;
import java.time.Duration;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.ObjectNode;

public class RustOdbcConnection implements Connection {

    private final String baseUrl;
    private final String sessionId;
    private final String dsn;
    private final String user;
    private final String charset;
    private final HttpClient httpClient;
    private final Properties clientInfo = new Properties();

    private boolean autoCommit = true;
    private boolean readOnly = false;
    private boolean closed = false;

    public RustOdbcConnection(String baseUrl, String sessionId, String dsn, String user, String charset) {
        this(baseUrl, sessionId, dsn, user, charset, TlsClientFactory.getPlainClient());
    }

    public RustOdbcConnection(String baseUrl, String sessionId, String dsn, String user, String charset, HttpClient httpClient) {
        this.baseUrl = baseUrl;
        this.sessionId = sessionId;
        this.dsn = dsn;
        this.user = user;
        this.charset = charset;
        this.httpClient = httpClient;
    }

    public String getBaseUrl() { return baseUrl; }
    public String getSessionId() { return sessionId; }
    public String getDsn() { return dsn; }
    public String getUser() { return user; }
    public String getCharset() { return charset; }
    public HttpClient getHttpClient() { return httpClient; }

    private void checkClosed() throws SQLException {
        if (closed) {
            throw new SQLException("Połączenie RustOdbcConnection zostało już zamknięte.");
        }
    }

    @Override
    public Statement createStatement() throws SQLException {
        checkClosed();
        return new RustOdbcStatement(this, null);
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        checkClosed();
        return new RustOdbcStatement(this, sql);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
        return createStatement();
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        return createStatement();
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException {
        checkClosed();
        if (this.autoCommit == autoCommit) {
            return;
        }

        try {
            ObjectNode payload = RustOdbcDriver.MAPPER.createObjectNode();
            payload.put("session_id", sessionId);
            payload.put("auto_commit", autoCommit);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/session/autocommit"))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(10))
                    .POST(HttpRequest.BodyPublishers.ofString(RustOdbcDriver.MAPPER.writeValueAsString(payload)))
                    .build();

            HttpResponse<String> response = this.httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() != 200) {
                JsonNode errNode = RustOdbcDriver.MAPPER.readTree(response.body());
                throw new SQLException("Błąd setAutoCommit z serwera Rust: " + errNode.path("error").asText(response.body()));
            }

            this.autoCommit = autoCommit;
        } catch (SQLException e) {
            throw e;
        } catch (Exception e) {
            throw new SQLException("Błąd komunikacji z mikroserwisem podczas setAutoCommit: " + e.getMessage(), e);
        }
    }

    @Override
    public boolean getAutoCommit() throws SQLException {
        checkClosed();
        return autoCommit;
    }

    @Override
    public void commit() throws SQLException {
        checkClosed();
        try {
            ObjectNode payload = RustOdbcDriver.MAPPER.createObjectNode();
            payload.put("session_id", sessionId);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/session/commit"))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(30))
                    .POST(HttpRequest.BodyPublishers.ofString(RustOdbcDriver.MAPPER.writeValueAsString(payload)))
                    .build();

            HttpResponse<String> response = this.httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() != 200) {
                JsonNode errNode = RustOdbcDriver.MAPPER.readTree(response.body());
                throw new SQLException("Błąd commit z serwera Rust: " + errNode.path("error").asText(response.body()));
            }
        } catch (SQLException e) {
            throw e;
        } catch (Exception e) {
            throw new SQLException("Błąd komunikacji z mikroserwisem podczas commit: " + e.getMessage(), e);
        }
    }

    @Override
    public void rollback() throws SQLException {
        checkClosed();
        try {
            ObjectNode payload = RustOdbcDriver.MAPPER.createObjectNode();
            payload.put("session_id", sessionId);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/session/rollback"))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(30))
                    .POST(HttpRequest.BodyPublishers.ofString(RustOdbcDriver.MAPPER.writeValueAsString(payload)))
                    .build();

            HttpResponse<String> response = this.httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() != 200) {
                JsonNode errNode = RustOdbcDriver.MAPPER.readTree(response.body());
                throw new SQLException("Błąd rollback z serwera Rust: " + errNode.path("error").asText(response.body()));
            }
        } catch (SQLException e) {
            throw e;
        } catch (Exception e) {
            throw new SQLException("Błąd komunikacji z mikroserwisem podczas rollback: " + e.getMessage(), e);
        }
    }

    @Override
    public void setReadOnly(boolean readOnly) throws SQLException {
        checkClosed();
        this.readOnly = readOnly;
    }

    @Override
    public boolean isReadOnly() throws SQLException {
        checkClosed();
        return readOnly;
    }

    @Override
    public boolean isValid(int timeout) throws SQLException {
        if (closed) {
            return false;
        }
        try {
            ObjectNode payload = RustOdbcDriver.MAPPER.createObjectNode();
            payload.put("session_id", sessionId);

            int sec = timeout > 0 ? Math.min(timeout, 5) : 5;

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/session/ping"))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(sec))
                    .POST(HttpRequest.BodyPublishers.ofString(RustOdbcDriver.MAPPER.writeValueAsString(payload)))
                    .build();

            HttpResponse<String> response = this.httpClient.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() != 200) {
                return false;
            }
            JsonNode root = RustOdbcDriver.MAPPER.readTree(response.body());
            return root.path("alive").asBoolean(true);
        } catch (Exception e) {
            return false;
        }
    }

    @Override
    public void close() throws SQLException {
        if (!closed) {
            closed = true;
            try {
                ObjectNode payload = RustOdbcDriver.MAPPER.createObjectNode();
                payload.put("session_id", sessionId);

                HttpRequest request = HttpRequest.newBuilder()
                        .uri(URI.create(baseUrl + "/session/close"))
                        .header("Content-Type", "application/json")
                        .timeout(Duration.ofSeconds(5))
                        .POST(HttpRequest.BodyPublishers.ofString(RustOdbcDriver.MAPPER.writeValueAsString(payload)))
                        .build();

                this.httpClient.send(request, HttpResponse.BodyHandlers.discarding());
            } catch (Exception ignored) {
            }
        }
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public DatabaseMetaData getMetaData() {
        return new RustOdbcDatabaseMetaData(this);
    }

    @Override
    public void setCatalog(String catalog) {}

    @Override
    public String getCatalog() {
        return dsn;
    }

    @Override
    public void setTransactionIsolation(int level) {}

    @Override
    public int getTransactionIsolation() {
        return Connection.TRANSACTION_READ_COMMITTED;
    }

    @Override
    public SQLWarning getWarnings() {
        return null;
    }

    @Override
    public void clearWarnings() {}

    @Override
    public void setHoldability(int holdability) {}

    @Override
    public int getHoldability() {
        return java.sql.ResultSet.HOLD_CURSORS_OVER_COMMIT;
    }

    @Override
    public Savepoint setSavepoint() throws SQLException {
        throw new SQLException("Savepointy nie są obsługiwane");
    }

    @Override
    public Savepoint setSavepoint(String name) throws SQLException {
        throw new SQLException("Savepointy nie są obsługiwane");
    }

    @Override
    public void rollback(Savepoint savepoint) throws SQLException {
        throw new SQLException("Savepointy nie są obsługiwane");
    }

    @Override
    public void releaseSavepoint(Savepoint savepoint) throws SQLException {
        throw new SQLException("Savepointy nie są obsługiwane");
    }

    @Override
    public void setClientInfo(String name, String value) {
        if (value != null) {
            clientInfo.setProperty(name, value);
        } else {
            clientInfo.remove(name);
        }
    }

    @Override
    public void setClientInfo(Properties properties) {
        if (properties != null) {
            clientInfo.putAll(properties);
        }
    }

    @Override
    public String getClientInfo(String name) {
        return clientInfo.getProperty(name);
    }

    @Override
    public Properties getClientInfo() {
        return clientInfo;
    }

    @Override
    public void setSchema(String schema) {}

    @Override
    public String getSchema() {
        return null;
    }

    @Override
    public void abort(Executor executor) throws SQLException {
        close();
    }

    @Override
    public void setNetworkTimeout(Executor executor, int milliseconds) {}

    @Override
    public int getNetworkTimeout() {
        return 0;
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        throw new SQLException("Nie można rozpakować do: " + iface.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this);
    }

    @Override
    public String toString() {
        return "RustOdbcConnection[dsn=" + dsn + ", sessionId=" + sessionId + ", closed=" + closed + "]";
    }

    // Pozostałe metody rzucają SQLException zamiast błędu dynamic proxy
    @Override public CallableStatement prepareCall(String sql) throws SQLException { throw new SQLException("CallableStatement nie jest obsługiwane"); }
    @Override public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws SQLException { throw new SQLException("CallableStatement nie jest obsługiwane"); }
    @Override public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException { throw new SQLException("CallableStatement nie jest obsługiwane"); }
    @Override public String nativeSQL(String sql) { return sql; }
    @Override public Map<String, Class<?>> getTypeMap() { return Map.of(); }
    @Override public void setTypeMap(Map<String, Class<?>> map) {}
    @Override public Clob createClob() throws SQLException { throw new SQLException("Clob nie jest obsługiwane"); }
    @Override public Blob createBlob() throws SQLException { throw new SQLException("Blob nie jest obsługiwane"); }
    @Override public NClob createNClob() throws SQLException { throw new SQLException("NClob nie jest obsługiwane"); }
    @Override public SQLXML createSQLXML() throws SQLException { throw new SQLException("SQLXML nie jest obsługiwane"); }
    @Override public Array createArrayOf(String typeName, Object[] elements) throws SQLException { throw new SQLException("createArrayOf nie jest obsługiwane"); }
    @Override public Struct createStruct(String typeName, Object[] attributes) throws SQLException { throw new SQLException("createStruct nie jest obsługiwane"); }
}
